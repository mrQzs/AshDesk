"""Ed25519 keys, manifests and signatures for ashdesk_update (docs/安装与打包.md「自动更新」).

Needs the `cryptography` package (pip install cryptography). Run from the repository root:
  python tools/sign_update.py genkey PRIVATE.pem PUBLIC.pem
      new key pair; the private key never goes into the repository
  python tools/sign_update.py header packaging/update_pubkey.pem updater/update_pubkey.h
      regenerate the public key header compiled into ashdesk_update (never edit the header by hand)
  python tools/sign_update.py manifest --version X.Y.Z --url URL [--min-version X.Y.Z] PACKAGE.zip OUT
      write the manifest OUT (size and sha256 taken from PACKAGE.zip) and its signature OUT.sig
  python tools/sign_update.py sign MANIFEST
      (re)sign an existing manifest into MANIFEST.sig

Signing reads the private key PEM from the path in the ASHDESK_UPDATE_KEY environment variable.
Before signing, the key's public half must match the key compiled into ashdesk_update
(updater/update_pubkey.h; --expect-pubkey takes another header or a public key PEM):
a signature from any other key is rejected by every installed client.
"""
import argparse
import hashlib
import os
import re
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey

KEY_ENV = "ASHDESK_UPDATE_KEY"
PUBKEY_HEADER = "updater/update_pubkey.h"
VERSION_RE = re.compile(r"(0|[1-9][0-9]{0,4})\.(0|[1-9][0-9]{0,4})\.(0|[1-9][0-9]{0,4})")
RAW = (serialization.Encoding.Raw, serialization.PublicFormat.Raw)


def genkey(args):
    private = Path(args.private)
    if private.exists():
        sys.exit(f"{private} already exists; refusing to overwrite a key")
    key = Ed25519PrivateKey.generate()
    private.write_bytes(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                          serialization.NoEncryption()))
    Path(args.public).write_bytes(key.public_key().public_bytes(serialization.Encoding.PEM,
                                                                serialization.PublicFormat.SubjectPublicKeyInfo))


def header(args):
    key = serialization.load_pem_public_key(Path(args.public).read_bytes())
    if not isinstance(key, Ed25519PublicKey):
        sys.exit(f"{args.public} is not an Ed25519 public key")
    raw = key.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    body = ",".join(f"0x{b:02x}" for b in raw)
    source = Path(args.public).as_posix()
    Path(args.out).write_bytes(
        (f"/* Generated by tools/sign_update.py header from {source}; do not edit. */\n"
         "#pragma once\n"
         f"static const unsigned char UPD_PUBKEY[32] = {{{body}}};\n").replace("\n", "\r\n").encode("ascii"))


def check_version(text, name):
    m = VERSION_RE.fullmatch(text)
    if not m or any(int(part) > 65535 for part in m.groups()):
        sys.exit(f"{name} must be MAJOR.MINOR.PATCH with parts 0..65535 and no leading zeros: {text!r}")


def load_private_key():
    path = os.environ.get(KEY_ENV)
    if not path:
        sys.exit(f"set {KEY_ENV} to the private key PEM path")
    key = serialization.load_pem_private_key(Path(path).read_bytes(), password=None)
    if not isinstance(key, Ed25519PrivateKey):
        sys.exit(f"{path} is not an Ed25519 private key")
    return key


def expected_pubkey(path):
    """The 32 raw bytes clients verify with: the UPD_PUBKEY array of a generated header, or a public key PEM."""
    try:
        data = Path(path).read_bytes()
    except OSError as e:
        sys.exit(f"--expect-pubkey {path}: {e.strerror}")
    if path.endswith(".h"):
        m = re.search(rb"UPD_PUBKEY\[32\]\s*=\s*\{([^}]*)\}", data)
        if not m:
            sys.exit(f"{path}: no UPD_PUBKEY[32] array (regenerate it with the header command)")
        raw = bytes(int(x, 16) for x in re.findall(rb"0x([0-9a-fA-F]{2})", m.group(1)))
    else:
        key = serialization.load_pem_public_key(data)
        if not isinstance(key, Ed25519PublicKey):
            sys.exit(f"{path} is not an Ed25519 public key")
        raw = key.public_bytes(*RAW)
    if len(raw) != 32:
        sys.exit(f"{path}: public key has {len(raw)} bytes, not 32")
    return raw


def signing_key(expect):
    """The private key, refused unless its public half is the one the clients carry."""
    key = load_private_key()
    mine, want = key.public_key().public_bytes(*RAW), expected_pubkey(expect)
    if mine != want:
        sys.exit(f"the key in {KEY_ENV} (public {mine.hex()[:16]}...) is not the one in {expect} "
                 f"({want.hex()[:16]}...): clients would reject this signature; nothing written")
    return key


def manifest(args):
    check_version(args.version, "--version")
    if args.min_version:
        check_version(args.min_version, "--min-version")
    if not re.fullmatch(r"https?://[\x21-\x7e]+", args.url):
        sys.exit("--url must be an absolute http(s) URL without spaces")
    key = signing_key(args.expect_pubkey)
    package = Path(args.package).read_bytes()
    lines = [f"version={args.version}", f"url={args.url}", f"size={len(package)}",
             f"sha256={hashlib.sha256(package).hexdigest()}"]
    if args.min_version:
        lines.append(f"min_version={args.min_version}")
    out = Path(args.out)
    data = ("\n".join(lines) + "\n").encode("ascii")
    out.write_bytes(data)
    Path(f"{out}.sig").write_bytes(key.sign(data))


def sign(args):
    key = signing_key(args.expect_pubkey)
    manifest_path = Path(args.manifest)
    Path(f"{manifest_path}.sig").write_bytes(key.sign(manifest_path.read_bytes()))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("genkey")
    p.add_argument("private")
    p.add_argument("public")
    p.set_defaults(run=genkey)
    p = sub.add_parser("header")
    p.add_argument("public")
    p.add_argument("out")
    p.set_defaults(run=header)
    p = sub.add_parser("manifest")
    p.add_argument("--version", required=True)
    p.add_argument("--url", required=True)
    p.add_argument("--min-version")
    p.add_argument("--expect-pubkey", default=PUBKEY_HEADER)
    p.add_argument("package")
    p.add_argument("out")
    p.set_defaults(run=manifest)
    p = sub.add_parser("sign")
    p.add_argument("--expect-pubkey", default=PUBKEY_HEADER)
    p.add_argument("manifest")
    p.set_defaults(run=sign)
    args = parser.parse_args()
    args.run(args)


if __name__ == "__main__":
    main()
